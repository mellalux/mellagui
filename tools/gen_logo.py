#!/usr/bin/env python3
"""Generate src/logo_data.h: the MellaGUI logo (tools/mella-logo.jpg, the "OÜ Mella Logo" of cms.mella.ee) cut to a circle, as premultiplied
ARGB at two sizes (LOGO_BIG for the About dialog, LOGO_SMALL for the panel button).

Usage: tools/gen_logo.py tools/mella-logo.jpg > src/logo_data.h
"""
import sys
from PIL import Image, ImageDraw

CX, CY, R = 600, 600, 520          # the circle (in the 1200x1200 source) that becomes the button
SIZES = (("BIG", 96), ("SMALL", 32))


def circle(src, size):
    big = size * 4
    img = src.crop((CX - R, CY - R, CX + R, CY + R)).convert("RGB").resize((big, big), Image.LANCZOS)
    mask = Image.new("L", (big, big), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, big - 1, big - 1), fill=255)
    img.putalpha(mask)
    return img.resize((size, size), Image.BOX)            # area average: crisp edge, anti-aliased rim


def main():
    src = Image.open(sys.argv[1])
    print("/* Generated by tools/gen_logo.py from tools/mella-logo.jpg - do not edit. Premultiplied ARGB, a circle with a soft rim. */")
    for name, size in SIZES:
        px = circle(src, size).load()
        print("#define LOGO_%s %d" % (name, size))
        print("static const uint32_t logo_%s[%d] = {" % (name.lower(), size * size))
        row = []
        for y in range(size):
            for x in range(size):
                r, g, b, a = px[x, y]
                row.append("0x%08x" % ((a << 24) | ((r * a // 255) << 16) | ((g * a // 255) << 8) | (b * a // 255)))
        for i in range(0, len(row), 8):
            print("    " + ", ".join(row[i:i + 8]) + ",")
        print("};")


main()
