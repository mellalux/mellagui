#!/bin/sh
# Writes the version header for the About dialog: what commit this build is, when it was made and when the repository was last pulled.
# Not a git checkout (a tarball) or no git: "unknown" and no pull time. Run by the Makefile on every build; the header is only replaced when it changed.
cd "$(dirname "$0")/.." || exit 0
count=unknown; hash=unknown; cdate=; pull=
if command -v git >/dev/null 2>&1 && git rev-parse --git-dir >/dev/null 2>&1; then
    count=$(git rev-list --count HEAD 2>/dev/null || echo unknown)
    hash=$(git rev-parse --short HEAD 2>/dev/null || echo unknown)
    if [ -n "$(git status --porcelain --untracked-files=no 2>/dev/null)" ]; then hash="$hash-dirty"; fi
    cdate=$(git log -1 --format=%cd --date=format:'%Y-%m-%d %H:%M' 2>/dev/null)
    fh=$(git rev-parse --git-path FETCH_HEAD 2>/dev/null)
    if [ -n "$fh" ] && [ -f "$fh" ]; then pull=$(date -d "@$(stat -c %Y "$fh")" '+%Y-%m-%d %H:%M' 2>/dev/null); fi
fi
cat <<H
/* generated by tools/gen_version.sh - do not edit */
#define LM_VERSION_COUNT "$count"
#define LM_VERSION_HASH "$hash"
#define LM_VERSION_COMMIT_DATE "$cdate"
#define LM_VERSION_PULL "$pull"
H
