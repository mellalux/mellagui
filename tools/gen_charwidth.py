#!/usr/bin/env python3
"""Writes client/charwidth.h: how many cells of a terminal a character takes, and the accented letters a base letter
and a combining mark make. From Python's unicodedata:  python3 tools/gen_charwidth.py > client/charwidth.h"""
import unicodedata as u


def ranges(pred):
    out = []
    for cp in range(0x300, 0x110000):
        if pred(cp):
            if out and out[-1][1] == cp - 1:
                out[-1][1] = cp
            else:
                out.append([cp, cp])
    return out


def zero(cp):
    return u.category(chr(cp)) in ("Mn", "Me", "Cf") or 0x1160 <= cp <= 0x11ff


def wide(cp):
    if zero(cp):
        return False
    return u.east_asian_width(chr(cp)) in ("W", "F") or 0x20000 <= cp <= 0x2fffd or 0x30000 <= cp <= 0x3fffd


compose = []
for cp in range(0xc0, 0x250):
    d = u.decomposition(chr(cp)).split()
    if len(d) == 2 and not d[0].startswith("<"):
        base, mark = int(d[0], 16), int(d[1], 16)
        if 0x300 <= mark <= 0x36f:
            compose.append((base, mark, cp))

print("#ifndef MELLAGUI_CHARWIDTH_H\n#define MELLAGUI_CHARWIDTH_H\n")
print("/* Generated by tools/gen_charwidth.py (Unicode %s): do not edit. */\n" % u.unidata_version)
print("#include <stdint.h>\n")
for name, pred in (("zero", zero), ("wide", wide)):
    print("static const uint32_t lm_%s_ranges[][2] = {" % name)
    r = ranges(pred)
    for i in range(0, len(r), 5):
        print("    " + " ".join("{ 0x%x, 0x%x }," % tuple(x) for x in r[i:i + 5]))
    print("};\n")
print("static const uint16_t lm_composed[][3] = {          /* base, combining mark, the letter */")
for i in range(0, len(compose), 4):
    print("    " + " ".join("{ 0x%x, 0x%x, 0x%x }," % x for x in compose[i:i + 4]))
print("};")
print('''
static inline int lm_in_ranges(const uint32_t (*r)[2], int n, uint32_t cp)
{
    int lo = 0, hi = n - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (cp < r[mid][0])
            hi = mid - 1;
        else if (cp > r[mid][1])
            lo = mid + 1;
        else
            return 1;
    }
    return 0;
}

/* 0 (a combining mark or an invisible format character), 1 or 2 cells. */
static inline int lm_char_width(uint32_t cp)
{
    if (cp < 0x300)
        return 1;
    if (lm_in_ranges(lm_zero_ranges, (int)(sizeof(lm_zero_ranges) / sizeof(lm_zero_ranges[0])), cp))
        return 0;
    return lm_in_ranges(lm_wide_ranges, (int)(sizeof(lm_wide_ranges) / sizeof(lm_wide_ranges[0])), cp) ? 2 : 1;
}

/* The one letter `base` and the combining `mark` make, 0 when there is none. */
static inline uint32_t lm_compose(uint32_t base, uint32_t mark)
{
    for (unsigned i = 0; i < sizeof(lm_composed) / sizeof(lm_composed[0]); i++)
        if (lm_composed[i][0] == base && lm_composed[i][1] == mark)
            return lm_composed[i][2];
    return 0;
}

#endif''')
