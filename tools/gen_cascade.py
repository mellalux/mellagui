"""Writes client/facedet_data.h from OpenCV's haarcascade_frontalface_default.xml (stump based, 24x24, 25 stages, 2913 weak classifiers).

usage: tools/gen_cascade.py haarcascade_frontalface_default.xml > client/facedet_data.h

The cascade is by Rainer Lienhart (Intel License Agreement for Open Source Computer Vision Library, see the notice the header carries).
"""
